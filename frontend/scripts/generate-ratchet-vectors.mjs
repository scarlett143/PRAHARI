/**
 * Record a ratchet conversation as interop vectors for the Python implementation.
 *
 * Cross-implementation agreement cannot be asserted by reading both files and hoping.
 * This runs a real conversation, capturing every ephemeral keypair as it is used, so the
 * other implementation can replay the exact same session and decrypt the exact same
 * bytes. If a KDF label, header layout or AAD framing ever drifts, the replay fails.
 *
 *   node scripts/generate-ratchet-vectors.mjs > ../backend/tests/vectors/ratchet_js_vectors.json
 */
import { x25519 } from "@noble/curves/ed25519.js";

import { bytesToBase64 } from "../src/crypto/bytes.js";
import {
  initReceiver,
  initSender,
  ratchetDecrypt,
  ratchetEncrypt,
} from "../src/crypto/ratchet.js";

const CHANNEL_ID = "interop-channel";
const ALICE_ID = "alice-uuid";
const BOB_ID = "bob-uuid";
const EPOCH = 0;

/** A keygen that hands out a fixed queue and records what it used. */
function recordingKeygen(pool, used) {
  let index = 0;
  return () => {
    const secret = pool[index++];
    if (!secret) throw new Error("ratchet consumed more keypairs than the pool holds");
    const keyPair = { secretKey: secret, publicKey: x25519.getPublicKey(secret) };
    used.push(bytesToBase64(secret));
    return keyPair;
  };
}

function randomSecrets(count) {
  return Array.from({ length: count }, () => crypto.getRandomValues(new Uint8Array(32)));
}

const sharedSecret = crypto.getRandomValues(new Uint8Array(32));
const bobIdentitySecret = crypto.getRandomValues(new Uint8Array(32));
const bobIdentity = {
  secretKey: bobIdentitySecret,
  publicKey: x25519.getPublicKey(bobIdentitySecret),
};

const alicePool = randomSecrets(8);
const bobPool = randomSecrets(8);
const aliceUsed = [];
const bobUsed = [];

const alice = await initSender(
  sharedSecret,
  bobIdentity.publicKey,
  recordingKeygen(alicePool, aliceUsed),
);
const bob = initReceiver(sharedSecret, bobIdentity, recordingKeygen(bobPool, bobUsed));

// Chosen to exercise both a one-sided burst and two direction flips, since those are the
// paths where the two implementations could diverge without either being obviously wrong.
const script = [
  ["alice", "first from the console"],
  ["alice", "second from the console"],
  ["bob", "reply from the aircraft"],
  ["alice", "after the flip"],
  ["alice", "still after the flip"],
  ["bob", "second reply"],
  ["alice", "final"],
];

const messages = [];
for (const [from, plaintext] of script) {
  const sender = from === "alice" ? alice : bob;
  const receiver = from === "alice" ? bob : alice;
  const senderId = from === "alice" ? ALICE_ID : BOB_ID;

  const envelope = await ratchetEncrypt(sender, plaintext, {
    senderId,
    channelId: CHANNEL_ID,
    epoch: EPOCH,
  });
  // Decrypt immediately so the recorded state transitions are the real ones.
  const roundTripped = await ratchetDecrypt(receiver, envelope, {
    senderId,
    channelId: CHANNEL_ID,
    epoch: EPOCH,
  });
  if (roundTripped !== plaintext) throw new Error("generator failed its own round trip");

  messages.push({ from, sender_id: senderId, plaintext, envelope, epoch: EPOCH });
}

process.stdout.write(
  `${JSON.stringify(
    {
      description:
        "Generated by frontend/scripts/generate-ratchet-vectors.mjs. Replayed by the " +
        "Python implementation to prove wire compatibility.",
      produced_by: "javascript",
      channel_id: CHANNEL_ID,
      alice_id: ALICE_ID,
      bob_id: BOB_ID,
      shared_secret: bytesToBase64(sharedSecret),
      bob_identity_secret: bytesToBase64(bobIdentity.secretKey),
      bob_identity_public: bytesToBase64(bobIdentity.publicKey),
      alice_keygen_queue: aliceUsed,
      bob_keygen_queue: bobUsed,
      messages,
    },
    null,
    2,
  )}\n`,
);
